export const GLYPH_W = 8;
export const GLYPH_H = 8;

export function measureText(text: string, scale = 1, spacing = 0): number {
  const n = text.length;
  return n * GLYPH_W * scale + Math.max(0, n - 1) * spacing * scale;
}

/** Draws bitmap text with the top-left corner at (x, y), fully pixel-snapped. */
export function drawBitmapText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  spacing = 0
): void {
  const ox = Math.round(x);
  const oy = Math.round(y);
  ctx.fillStyle = color;
  let cursor = ox;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS[' '];
    for (let row = 0; row < GLYPH_H; row++) {
      const bits = glyph[row];
      for (let col = 0; col < GLYPH_W; col++) {
        if (bits[col] === '1') {
          ctx.fillRect(cursor + col * scale, oy + row * scale, scale, scale);
        }
      }
    }
    cursor += GLYPH_W * scale + spacing * scale;
  }
}
